CREATE TABLE tb_user (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    username VARCHAR(100) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL
);

CREATE TABLE tb_item (
    item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    description TEXT NOT NULL,
    category VARCHAR(50) NOT NULL,
    local_found VARCHAR(150) NOT NULL,
    time_found DATE NOT NULL,
    redeem_local VARCHAR(150) NOT NULL,
    img_url VARCHAR(500),
    status VARCHAR(30) NOT NULL DEFAULT 'UNCLAIMED'
);

CREATE INDEX idx_item_status ON tb_item(status);
CREATE INDEX idx_item_local_found ON tb_item(local_found);